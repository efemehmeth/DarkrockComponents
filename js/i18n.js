let currentLang = localStorage.getItem('darkrock_lang') || 'en';

function setLanguage(lang, animate = true) {
  currentLang = lang;
  localStorage.setItem('darkrock_lang', lang);
  document.documentElement.lang = lang;

  const elements = document.querySelectorAll('[data-i18n]');

  if (animate) {
    elements.forEach(el => el.classList.add('i18n-changing'));
    setTimeout(() => {
      updateContent(lang, elements);
      setTimeout(() => {
        elements.forEach(el => el.classList.remove('i18n-changing'));
      }, 50);
    }, 200);
  } else {
    updateContent(lang, elements);
  }
}

function updateContent(lang, elements) {
  const trans = translations[lang];
  if (!trans) return;

  // Update Page Title and Meta Description
  const currentPage = location.pathname.split('/').pop().replace('.html', '') || 'index';
  const titleKey = `meta-title-${currentPage}`;
  const descKey = `meta-desc-${currentPage}`;
  
  if (trans[titleKey]) document.title = trans[titleKey];
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && trans[descKey]) metaDesc.setAttribute('content', trans[descKey]);

  // Update Elements
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (trans[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = trans[key];
      } else if (el.tagName === 'SELECT') {
        // Handle select placeholders (first disabled option)
        const firstOpt = el.querySelector('option[disabled]');
        if (firstOpt) firstOpt.textContent = trans[key];
      } else {
        el.innerHTML = trans[key];
      }
    }
  });

  // Special handling for lang switcher
  const langBtn = document.getElementById('lang-switcher-btn');
  if (langBtn) {
    langBtn.innerHTML = `<span>${trans['lang-name']}</span>`;
  }
}

function cycleLanguage() {
  const langs = ['en', 'tr', 'de'];
  let idx = (langs.indexOf(currentLang) + 1) % langs.length;
  setLanguage(langs[idx], true);
}

document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang, false);
  const langBtn = document.getElementById('lang-switcher-btn');
  if (langBtn) {
    langBtn.addEventListener('click', (e) => {
      e.preventDefault();
      cycleLanguage();
    });
  }
});
